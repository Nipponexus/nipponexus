MARGIN = 0.25  # bboxは粗いので緩衝を取る

def check(row):
    """row: dict風(prefecture, description_ja, latitude, longitude)。戻り値 (ok, reason)"""
    pref = row["prefecture"]
    if not pref:
        return True, "prefecture NULL(全国行事として許容)"
    if pref not in PREFS:
        return False, "未知の県名: %s" % pref
    d = row["description_ja"] or ""
    hits = [p for p in PREFS if p in d]
    if hits and pref not in hits:
        return False, "desc矛盾: DB=%s desc=%s" % (pref, "/".join(hits))
    lat, lon = row["latitude"], row["longitude"]
    if lat is not None and lon is not None and pref in BBOX:
        a, b, c, e = BBOX[pref]
        if not (a-MARGIN <= lat <= b+MARGIN and c-MARGIN <= lon <= e+MARGIN):
            return False, "座標が%sのbbox外: (%.3f,%.3f)" % (pref, lat, lon)
    return True, "ok"

def assert_ok(conn, qid):
    """呼び出し元の row_factory を変更しない(2026-08-07修正)。"""
    cur = conn.execute("SELECT prefecture,description_ja,latitude,longitude "
                       "FROM festivals WHERE qid=?", (qid,))
    r = cur.fetchone()
    if r is None:
        raise AssertionError("nxpref: qid %s が見つからない" % qid)
    names = [d[0] for d in cur.description]
    ok, why = check(dict(zip(names, tuple(r))))
    if not ok:
        raise AssertionError("nxpref BLOCK %s: %s" % (qid, why))
    return True
